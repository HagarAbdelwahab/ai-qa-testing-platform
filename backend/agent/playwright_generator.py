"""
Writes generated Playwright .spec.ts files into the Playwright repo,
with Jira + AIO tracking links embedded in each file.
"""
import os
import json
from pathlib import Path
import config


def write_spec_file(
    story_key: str,
    story_title: str,
    spec_content: str,
    aio_tc_keys: list[str],
    test_set_key: str,
    cycle_name: str,
) -> str:
    """
    Write a Playwright spec to the configured repo.
    Returns the path of the written file.
    """
    repo = Path(config.PLAYWRIGHT_REPO_PATH)
    tests_dir = repo / "tests" / "generated"
    tests_dir.mkdir(parents=True, exist_ok=True)

    filename = f"{story_key.lower().replace('-', '_')}.spec.ts"
    file_path = tests_dir / filename

    jira_url = f"{config.JIRA_BASE_URL}/browse/{story_key}"
    aio_keys_str = ", ".join(aio_tc_keys)

    header = f"""// =============================================================================
// JIRA Story  : {story_key} — {story_title}
// JIRA URL    : {jira_url}
// AIO Test Set: {test_set_key}
// AIO Cycle   : {cycle_name}
// AIO Cases   : {aio_keys_str}
// Generated by: AI QA Agent (Claude claude-opus-4-6)
// =============================================================================

"""
    full_content = header + spec_content

    file_path.write_text(full_content, encoding="utf-8")
    print(f"  Playwright spec written: {file_path}")
    return str(file_path)


def write_tracking_index(entries: list[dict]) -> str:
    """
    Maintain a JSON index file mapping story keys to their generated specs and AIO artifacts.
    entries: list of dicts with story_key, story_title, spec_path, aio_tc_keys, test_set_key, cycle_name
    """
    repo = Path(config.PLAYWRIGHT_REPO_PATH)
    index_path = repo / "tests" / "generated" / "tracking_index.json"

    existing = {}
    if index_path.exists():
        with open(index_path) as f:
            existing = json.load(f)

    for entry in entries:
        existing[entry["story_key"]] = entry

    index_path.write_text(json.dumps(existing, indent=2, ensure_ascii=False))
    print(f"  Tracking index updated: {index_path}")
    return str(index_path)
